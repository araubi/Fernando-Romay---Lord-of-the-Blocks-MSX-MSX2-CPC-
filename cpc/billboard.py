NARROW = False
def glyph(ch):
    if NARROW: return N[ch].split('|')
    return [r for r in G[ch].strip().split('|')]
def text_bits(s, gap=1, space=3):
    cols = []
    for ch in s:
        if ch == ' ': cols += [[0] * 11] * space; continue
        g = glyph(ch); w = len(g[0])
        for x in range(w): cols.append([g[y][x] == '#' for y in range(11)])
        cols += [[0] * 11] * gap
    cols = cols[:-gap]
    return np.array(cols, bool).T
def outline(t):
    from scipy import ndimage
    d = ndimage.binary_dilation(np.pad(t, 1), structure=np.ones((3, 3), bool))
    return np.pad(t, 1), d
def draw(a):
    a = a.copy()
    orig = a.copy()
    amstrad = orig[33:47, 33:96].copy()
    Y0, Y1 = 33, 47            # filas interiores
    # limpiar interior
    for y in range(32, 48):
        for x in range(33, 224): a[y, x] = 1
    sep1, sep2 = 81, 145
    for y in range(32, 48):
        a[y, sep1] = 2; a[y, sep2] = 2
    a[33:47, sep1 + 1:sep1 + 1 + 63] = amstrad
    def put(text, x0, x1):
        t, d = outline(text_bits(text))
        h, w = t.shape
        x = x0 + (x1 - x0 - w) // 2; y = 34
        for yy in range(h):
            for xx in range(w):
                if t[yy, xx]: a[y + yy, x + xx] = 0
                elif d[yy, xx]: a[y + yy, x + xx] = 2
    put('Mirinda', 33, sep1)
    global NARROW
    NARROW = True
    put('ZX CALCULATOR', sep2 + 1, 224)
    NARROW = False
    return a
