ORDER = ' !*-.0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ'
def rows(ch):
    return [int(r.replace('.', '0').replace('#', '1'), 2) << 3 for r in G.get(ch, G[' '])]
def data():
    """tabla de 7 bytes por caracter (bit 7 = pixel izquierdo), en el orden ORDER"""
    return b''.join(bytes(rows(c)) for c in ORDER)
def render(P, x, y, text, pen, bg=1):
    for i, ch in enumerate(text):
        for dy in range(8):
            for dx in range(6):
                P[y + dy, x + 6 * i + dx] = bg
        for dy, r in enumerate(rows(ch)):
            for dx in range(5):
                if r & (0x80 >> dx): P[y + dy, x + 6 * i + dx] = pen
