def flip_bit(F2, base_e, ystart, x, y):
    # bitmap de 30 bytes de ancho dibujado en pantalla en (8, ystart)
    bx=x-8; by=y-ystart
    a=(0xC394-0x8534)+(base_e-0xE740)+by*30+bx//8
    F2[a]^=0x80>>(bx%8)
