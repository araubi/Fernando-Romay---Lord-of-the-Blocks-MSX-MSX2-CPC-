"""Punteria por jugador (V93EB bit 7 = tira el jugador 1).
ITURRIAGA: error total del tiro x0.9 (10% mas preciso).
F. ROMAY: el termino de distancia pesa un 10% mas (x55/70 en lugar de x50/70).
Codigo en AF9Ah (restos sin uso dentro del fichero 3)."""
ORG=0xAF9A
MUL16,DIV16=0xD724,0xD73B
def asm():
    w=lambda v:[v&255,v>>8]
    dist=[0x01,0x32,0x00, 0xF5, 0x3A,*w(0x93EB), 0x17, 0x38,0x02, 0x0E,0x37, 0xF1, 0xC9]
    tot=[0x3A,*w(0x93EB), 0x17, 0x30,0x0C, 0x01,0x09,0x00, 0xCD,*w(MUL16), 0x01,0x0A,0x00, 0xCD,*w(DIV16),
         0xED,0x5F, 0xE6,0x0F, 0xC9]
    return bytes(dist+tot), ORG, ORG+len(dist)
def apply(F1,F2,F3):
    code,DIST,TOT=asm()
    assert ORG+len(code)<=0xAFC8
    o=ORG-0x84D0; F3[o:o+len(code)]=code
    i=0x8B35-0x84D0; assert bytes(F3[i:i+3])==bytes([0x01,0x32,0x00]); F3[i:i+3]=bytes([0xCD,DIST&255,DIST>>8])
    i=0x8B84-0x84D0; assert bytes(F3[i:i+4])==bytes([0xED,0x5F,0xE6,0x0F]); F3[i:i+4]=bytes([0xCD,TOT&255,TOT>>8,0x00])
