"""Controles por defecto: J1 (ITURRIAGA) cursores + ESPACIO; J2 (F. ROMAY) W/S/A/D + SHIFT; pausa P."""
UP,DOWN,LEFT,RIGHT,SPACE=0x45,0x46,0x44,0x47,0x40
W,S,A,D,SHIFT,P=0x2C,0x28,0x16,0x19,0x30,0x25
def put(F3,addr,val): F3[addr-0x84D0]=val
def get(F3,addr): return F3[addr-0x84D0]
def apply(F1,F2,F3):
    # listas mostradas en la pantalla de redefinicion: arriba, abajo, izq, der, accion, pausa
    assert bytes(F3[0xAE57-0x84D0:0xAE5D-0x84D0])==bytes([0x01,0x26,0x19,0x1B,0x2F,0x06])
    assert bytes(F3[0xAE67-0x84D0:0xAE6D-0x84D0])==bytes([0x45,0x46,0x44,0x47,0x3F,0x06])
    F3[0xAE57-0x84D0:0xAE5D-0x84D0]=bytes([UP,DOWN,LEFT,RIGHT,SPACE,P])
    F3[0xAE67-0x84D0:0xAE6D-0x84D0]=bytes([W,S,A,D,SHIFT,P])
    # inmediatos de la lectura de teclas
    for addr,v in zip((0xAF0E,0xAF17,0xAF2A,0xAF33,0xAF46),(UP,DOWN,LEFT,RIGHT,SPACE)):
        assert get(F3,addr-1)==0x3E; put(F3,addr,v)
    for addr,v in zip((0xAF55,0xAF5E,0xAF71,0xAF7A,0xAF8D),(W,S,A,D,SHIFT)):
        assert get(F3,addr-1)==0x3E; put(F3,addr,v)
    # pausa
    assert get(F3,0x8679)==0xFE and get(F3,0x867A)==0x06
    put(F3,0x867A,P)
